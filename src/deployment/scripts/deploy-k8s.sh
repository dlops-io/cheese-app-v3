#!/usr/bin/env bash
# Deploy the workloads in k8s/ onto the deploy_k8s cluster, with the images deploy_images pushed.
# Everything specific to your project goes in a generated overlay, so k8s/ stays plain YAML.
#   ./scripts/deploy-k8s.sh                  (STACK=dev by default)
#   RELOAD_BOOKS=1 ./scripts/deploy-k8s.sh   load the books into Chroma again
set -euo pipefail
cd "$(dirname -- "${BASH_SOURCE[0]}")/.."
stack="${STACK:-dev}"
output() { (cd "$1" && pulumi stack output --stack "${stack}" "$2"); }

# The cluster, from its stack; always this context, never whatever kubectl last pointed at
cluster="$(output deploy_k8s cluster_name)"
zone="$(output deploy_k8s cluster_location)"
gcloud container clusters get-credentials "${cluster}" --zone "${zone}" --project "${GCP_PROJECT}"
context="gke_${GCP_PROJECT}_${zone}_${cluster}"

# image <name in k8s/> <ref from deploy_images>: name:tag@digest -> a kustomize images entry
image() {
    local ref="$2" name
    name="${ref%@*}"
    printf '  - name: %s\n    newName: %s\n    newTag: "%s"\n    digest: %s\n' \
        "$1" "${name%:*}" "${name##*:}" "${ref#*@}"
}

overlay=".local/k8s-${stack}"
mkdir -p "${overlay}/load-vector-db"
service_account="$(output deploy_base app_service_account)"
{
    echo "# Generated by scripts/deploy-k8s.sh: k8s/ with this project's settings. Do not edit."
    echo "resources: [../../k8s]"
    echo "images:"
    image cheese-app-api-service "$(output deploy_images api_service_ref)"
    image cheese-app-frontend-react "$(output deploy_images frontend_react_ref)"
    cat <<YAML
configMapGenerator:
  - name: api-config
    behavior: merge
    literals:
      - GCP_PROJECT=${GCP_PROJECT}
      - CHAT_BUCKET=$(output deploy_base chat_bucket)
generatorOptions:
  disableNameSuffixHash: true
patches:
  - target: { kind: ServiceAccount, name: api-service }
    patch: |
      - op: add
        path: /metadata/annotations
        value:
          iam.gke.io/gcp-service-account: ${service_account}
  - target: { kind: Gateway, name: cheese-app }
    patch: |
      - op: replace
        path: /spec/addresses/0/value
        value: $(output deploy_base gateway_ip_name)
YAML
} > "${overlay}/kustomization.yaml"
{
    echo "# Generated by scripts/deploy-k8s.sh. Do not edit."
    echo "resources: [../../../k8s/load-vector-db]"
    echo "images:"
    image cheese-app-vector-db-cli "$(output deploy_images vector_db_cli_ref)"
} > "${overlay}/load-vector-db/kustomization.yaml"

kubectl --context "${context}" apply -k "${overlay}"
kubectl --context "${context}" -n cheese-app rollout status statefulset/vector-db --timeout=300s

# Once per cluster: Chroma keeps the books on its disk, and a Job cannot be changed after it is created
if [[ "${RELOAD_BOOKS:-}" == 1 ]] || ! kubectl --context "${context}" -n cheese-app get job load-vector-db >/dev/null 2>&1; then
    kubectl --context "${context}" -n cheese-app delete job load-vector-db --ignore-not-found
    kubectl --context "${context}" apply -k "${overlay}/load-vector-db"
    kubectl --context "${context}" -n cheese-app wait job/load-vector-db --for=condition=Complete --timeout=600s
fi

for deployment in api-service frontend-react; do
    kubectl --context "${context}" -n cheese-app rollout status "deployment/${deployment}" --timeout=420s
done
kubectl --context "${context}" -n cheese-app wait gateway/cheese-app --for=condition=Programmed --timeout=600s

cat <<MSG

Deployed to ${context}. The load balancer can take a few minutes more before it answers:
  App:    http://$(output deploy_base gateway_ip)
  Watch:  kubectl -n cheese-app get pods,hpa -w
MSG
